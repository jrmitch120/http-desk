pub const HTTP_METHODS: &[&str] = &["get", "put", "post", "delete", "options", "head", "patch", "trace"];
const BOUNDARY: &str = "WebAppBoundary";
const MAX_COMMENT_LINES: usize = 40;

pub(crate) struct Op<'a> {
    pub info: OperationInfo,
    pub path_item: &'a Value,
    pub op: &'a Value,
}

pub(crate) fn collect_operations(root: &Value) -> Vec<Op<'_>> {
    let ctx = Ctx::new(root);
    let mut out: Vec<Op> = Vec::new();
    let mut seen = std::collections::HashSet::new();
    let Some(paths) = root.get("paths").and_then(Value::as_object) else { return out };
    for (path, item) in paths {
        let item = ctx.deref(item);
        let Some(item_obj) = item.as_object() else { continue };
        for (method, op) in item_obj {
            if !HTTP_METHODS.contains(&method.as_str()) || !op.is_object() {
                continue;
            }
            let s = |k: &str| op.get(k).and_then(Value::as_str).map(str::to_string);
            let method = method.to_ascii_uppercase();
            let operation_id = s("operationId").filter(|o| !o.trim().is_empty());
            let fallback = format!("{method} {path}");
            let id = match &operation_id {
                Some(o) if seen.insert(o.clone()) => o.clone(),
                _ => {
                    seen.insert(fallback.clone());
                    fallback
                }
            };
            let tags = op
                .get("tags")
                .and_then(Value::as_array)
                .map(|t| t.iter().filter_map(Value::as_str).map(str::to_string).collect())
                .unwrap_or_default();
            out.push(Op {
                info: OperationInfo {
                    id,
                    method,
                    path: path.clone(),
                    summary: s("summary").filter(|s| !s.trim().is_empty()),
                    operation_id,
                    tags,
                    deprecated: op.get("deprecated").and_then(Value::as_bool).unwrap_or(false),
                },
                path_item: item,
                op,
            });
        }
    }
    out
}

pub(crate) fn generate(doc: &OpenApiDoc, opts: &GenerateOptions) -> GenerationOutput {
    let root = doc.value();
    let ctx = Ctx::new(root);
    let base_var = match opts.base_url_variable.trim() {
        "" => "baseUrl",
        v => v,
    };
    let summary_title = root.pointer("/info/title").and_then(Value::as_str).unwrap_or("API");
    let summary_version = root.pointer("/info/version").and_then(Value::as_str).unwrap_or("");

    let ops: Vec<Op> = collect_operations(root)
        .into_iter()
        .filter(|o| opts.operation_ids.is_empty() || opts.operation_ids.contains(&o.info.id))
        .collect();

    // Group in order of first appearance.
    let mut groups: Vec<(String, Vec<&Op>)> = Vec::new();
    for op in &ops {
        let key = match opts.grouping {
            Grouping::Tag => op.info.tags.first().cloned().unwrap_or_else(|| "default".into()),
            Grouping::Path => first_segment(&op.info.path),
            Grouping::Single => String::new(),
        };
        match groups.iter_mut().find(|(k, _)| *k == key) {
            Some((_, list)) => list.push(op),
            None => groups.push((key, vec![op])),
        }
    }

    let mut secrets: Vec<String> = Vec::new();
    let mut files = Vec::new();
    let mut used_names: Vec<String> = Vec::new();
    for (key, list) in groups {
        let stem = match opts.grouping {
            Grouping::Single => {
                let name = opts.single_file_name.clone().filter(|n| !n.trim().is_empty());
                match name {
                    Some(n) => n.trim().trim_end_matches(".http").to_string(),
                    None => slug(summary_title),
                }
            }
            _ => slug(&key),
        };
        let file_name = unique_name(&stem, &mut used_names);

        let mut file = HttpFile::default();
        let mut title_line = format!("# Generated by HttpDesk from \"{summary_title}\"");
        if !summary_version.is_empty() {
            title_line.push_str(&format!(" {summary_version}"));
        }
        file.header.comments.push(title_line);
        if opts.grouping == Grouping::Tag {
            if let Some(desc) = tag_description(root, &key) {
                file.header.comments.push(format!("# {key}: {desc}"));
            }
        }
        for op in list {
            let req = build_request(&ctx, op, base_var, opts.param_descriptions, &mut file.header.variables, &mut secrets);
            file.requests.push(req);
        }
        files.push(GeneratedFile { relative_path: file_name, file });
    }

    let environments = environments(&doc.servers(), base_var, &secrets);
    let mut warnings = doc.warnings.clone();
    for w in ctx.warnings.into_inner() {
        if !warnings.contains(&w) {
            warnings.push(w);
        }
    }
    GenerationOutput { files, environments, warnings }
}

fn environments(servers: &[ServerInfo], base_var: &str, secrets: &[String]) -> Vec<GeneratedEnvironment> {
    let secrets: Vec<(String, String)> = secrets.iter().map(|s| (s.clone(), String::new())).collect();
    if servers.is_empty() {
        return vec![GeneratedEnvironment {
            name: "default".into(),
            variables: vec![(base_var.to_string(), "http://localhost".into())],
            secrets,
        }];
    }
    let mut used = Vec::new();
    servers
        .iter()
        .enumerate()
        .map(|(i, s)| {
            let stem = match s.description.as_deref().map(slug).filter(|d| !d.is_empty() && d != "api") {
                Some(d) => d,
                None if servers.len() == 1 => "default".into(),
                None => format!("server{}", i + 1),
            };
            GeneratedEnvironment {
                name: unique_env(&stem, &mut used),
                variables: vec![(base_var.to_string(), s.url.clone())],
                secrets: secrets.clone(),
            }
        })
        .collect()
}

fn unique_env(stem: &str, used: &mut Vec<String>) -> String {
    let mut name = stem.to_string();
    let mut n = 2;
    while used.contains(&name) {
        name = format!("{stem}-{n}");
        n += 1;
    }
    used.push(name.clone());
    name
}

fn unique_name(stem: &str, used: &mut Vec<String>) -> String {
    let stem = if stem.is_empty() { "api" } else { stem };
    let mut name = format!("{stem}.http");
    let mut n = 2;
    while used.iter().any(|u| u.eq_ignore_ascii_case(&name)) {
        name = format!("{stem}-{n}.http");
        n += 1;
    }
    used.push(name.clone());
    name
}

fn tag_description(root: &Value, tag: &str) -> Option<String> {
    root.get("tags")?
        .as_array()?
        .iter()
        .find(|t| t.get("name").and_then(Value::as_str) == Some(tag))?
        .get("description")?
        .as_str()?
        .lines()
        .find(|l| !l.trim().is_empty())
        .map(|l| l.trim().to_string())
}

fn first_segment(path: &str) -> String {
    let seg = path.split('/').find(|s| !s.is_empty()).unwrap_or("root");
    seg.trim_matches(|c| c == '{' || c == '}').to_string()
}

pub(crate) fn slug(s: &str) -> String {
    let mut out = String::new();
    for c in s.chars() {
        if c.is_ascii_alphanumeric() {
            out.push(c.to_ascii_lowercase());
        } else if !out.ends_with('-') && !out.is_empty() {
            out.push('-');
        }
    }
    let out = out.trim_end_matches('-').to_string();
    if out.is_empty() {
        "api".into()
    } else {
        out
    }
}

/// Characters allowed in `.http` variable names.
fn sanitize_var(s: &str) -> String {
    let out: String = s
        .chars()
        .map(|c| if c.is_alphanumeric() || matches!(c, '_' | '-' | '.') { c } else { '_' })
        .collect();
    if out.is_empty() {
        "value".into()
    } else {
        out
    }
}

fn sanitize_ident(s: &str) -> String {
    s.chars().map(|c| if c.is_ascii_alphanumeric() || c == '_' || c == '-' { c } else { '_' }).collect()
}

/// `GET /pets/{petId}` → `getPetsPetId`.
fn derived_operation_id(method: &str, path: &str) -> String {
    let mut out = method.to_ascii_lowercase();
    for word in path.split(|c: char| !c.is_ascii_alphanumeric()).filter(|w| !w.is_empty()) {
        let mut chars = word.chars();
        if let Some(first) = chars.next() {
            out.push(first.to_ascii_uppercase());
            out.extend(chars);
        }
    }
    out
}

/// Percent-encodes characters that would break a query string or form body.
pub(crate) fn encode_component(s: &str) -> String {
    let mut out = String::new();
    for b in s.bytes() {
        let c = b as char;
        if c.is_ascii_alphanumeric() || "-._~:/@!$'()*,;".contains(c) {
            out.push(c);
        } else {
            out.push_str(&format!("%{b:02X}"));
        }
    }
    out
}

fn value_to_string(v: &Value) -> String {
    match v {
        Value::Null => String::new(),
        Value::String(s) => s.clone(),
        Value::Array(a) => a.iter().map(value_to_string).collect::<Vec<_>>().join(","),
        Value::Object(_) => v.to_string(),
        other => other.to_string(),
    }
}

fn single_line(s: &str) -> String {
    s.split_whitespace().collect::<Vec<_>>().join(" ")
}

/// Example for a parameter or media type object: `example`, first of
/// `examples`, then the schema.
fn object_example<'a>(ctx: &Ctx<'a>, obj: &'a Value) -> Option<Value> {
    if let Some(v) = obj.get("example") {
        return Some(v.clone());
    }
    if let Some(examples) = obj.get("examples").and_then(Value::as_object) {
        for ex in examples.values() {
            if let Some(v) = ctx.deref(ex).get("value") {
                return Some(v.clone());
            }
        }
    }
    if let Some(schema) = obj.get("schema") {
        return Some(ctx.schema_example(schema));
    }
    None
}

fn param_example<'a>(ctx: &Ctx<'a>, p: &'a Value) -> Value {
    if let Some(v) = object_example(ctx, p) {
        return v;
    }
    if let Some(content) = p.get("content").and_then(Value::as_object) {
        if let Some(media) = content.values().next() {
            if let Some(v) = object_example(ctx, ctx.deref(media)) {
                return v;
            }
        }
    }
    Value::Null
}

const MAX_DOC_CHARS: usize = 240;
const MAX_DOC_ENUM: usize = 8;

/// One-line documentation for a parameter: the first paragraph of its
/// description plus required / deprecated / allowed values / default.
fn param_doc<'a>(ctx: &Ctx<'a>, p: &'a Value, required: bool) -> String {
    let schema = p.get("schema").map(|s| ctx.deref(s));
    fn text(v: Option<&Value>) -> Option<&str> {
        v.and_then(Value::as_str).map(str::trim).filter(|s| !s.is_empty())
    }
    let mut parts: Vec<String> = Vec::new();
    if let Some(desc) = text(p.get("description")).or_else(|| text(schema.and_then(|s| s.get("description")))) {
        // First paragraph; its lines become sentences so they don't run together.
        let first = desc.split("\n\n").next().unwrap_or(desc);
        let sentences: Vec<String> = first
            .lines()
            .map(single_line)
            .filter(|l| !l.is_empty())
            .map(|l| if l.ends_with(['.', '!', '?', ':', ';', ',']) { l } else { format!("{l}.") })
            .collect();
        let mut line = sentences.join(" ");
        if line.chars().count() > MAX_DOC_CHARS {
            line = line.chars().take(MAX_DOC_CHARS - 1).collect::<String>().trim_end().to_string() + "…";
        }
        parts.push(line);
    }
    if required {
        parts.push("Required.".into());
    }
    if p.get("deprecated").and_then(Value::as_bool).unwrap_or(false) {
        parts.push("Deprecated.".into());
    }
    let values = schema.and_then(|s| {
        s.get("enum").or_else(|| s.get("items").map(|i| ctx.deref(i)).and_then(|i| i.get("enum")))
    });
    if let Some(values) = values.and_then(Value::as_array).filter(|v| !v.is_empty()) {
        let shown: Vec<String> = values.iter().take(MAX_DOC_ENUM).map(value_to_string).collect();
        let more = if values.len() > MAX_DOC_ENUM { format!(", … ({} total)", values.len()) } else { String::new() };
        parts.push(format!("One of: {}{more}.", shown.join(", ")));
    }
    if let Some(default) = schema.and_then(|s| s.get("default")).filter(|d| !d.is_null()) {
        parts.push(format!("Default: {}.", value_to_string(default)));
    }
    parts.join(" ")
}

fn merged_parameters<'a>(ctx: &Ctx<'a>, op: &Op<'a>) -> Vec<&'a Value> {
    let mut out: Vec<&'a Value> = Vec::new();
    let lists = [op.path_item.get("parameters"), op.op.get("parameters")];
    for list in lists.into_iter().flatten().filter_map(Value::as_array) {
        for p in list {
            let p = ctx.deref(p);
            let key = |v: &Value| {
                (v.get("name").and_then(Value::as_str).map(str::to_string), v.get("in").and_then(Value::as_str).map(str::to_string))
            };
            let k = key(p);
            match out.iter_mut().find(|e| key(e) == k) {
                Some(slot) => *slot = p,
                None => out.push(p),
            }
        }
    }
    out
}

fn build_request<'a>(
    ctx: &Ctx<'a>,
    op: &Op<'a>,
    base_var: &str,
    with_docs: bool,
    file_vars: &mut Vec<Variable>,
    secrets: &mut Vec<String>,
) -> Request {
    let info = &op.info;
    let o = op.op;
    let mut req = Request { method: info.method.clone(), ..Default::default() };

    req.name = info
        .summary
        .as_deref()
        .map(single_line)
        .or_else(|| info.operation_id.clone())
        .unwrap_or_else(|| format!("{} {}", info.method, info.path));
    if info.deprecated {
        req.comments.push("DEPRECATED".into());
    }
    if let Some(desc) = o.get("description").and_then(Value::as_str) {
        let lines: Vec<&str> = desc.lines().map(str::trim_end).collect();
        let start = lines.iter().position(|l| !l.trim().is_empty()).unwrap_or(lines.len());
        let end = lines.iter().rposition(|l| !l.trim().is_empty()).map_or(start, |e| e + 1);
        for l in lines[start..end].iter().take(MAX_COMMENT_LINES) {
            // A leading `@`, even after indentation, would be read back as a directive.
            let body = l.trim_start();
            req.comments.push(match body.strip_prefix('@') {
                Some(rest) => format!("{}@ {rest}", &l[..l.len() - body.len()]),
                None => l.to_string(),
            });
        }
    }
    let id = info.operation_id.as_deref().map(sanitize_ident).unwrap_or_else(|| derived_operation_id(&info.method, &info.path));
    req.directives.push(Directive { name: "name".into(), value: id });

    // ---- URL + path params ----
    let params = merged_parameters(ctx, op);
    let mut path = info.path.clone();
    let mut path_names: Vec<String> = Vec::new();
    {
        let mut rest = info.path.as_str();
        while let Some(start) = rest.find('{') {
            let Some(len) = rest[start..].find('}') else { break };
            path_names.push(rest[start + 1..start + len].to_string());
            rest = &rest[start + len + 1..];
        }
    }
    for name in &path_names {
        let var = sanitize_var(name);
        path = path.replace(&format!("{{{name}}}"), &format!("{{{{{var}}}}}"));
        let declared = params.iter().find(|p| {
            p.get("in").and_then(Value::as_str) == Some("path") && p.get("name").and_then(Value::as_str) == Some(name)
        });
        let value = match declared {
            Some(p) => value_to_string(&param_example(ctx, p)),
            None => {
                ctx.warn(format!("{} {}: path parameter `{name}` is not declared", info.method, info.path));
                String::new()
            }
        };
        if !file_vars.iter().any(|v| v.name == var) {
            file_vars.push(Variable { name: var, value: if value.is_empty() { name.clone() } else { value } });
        }
    }
    req.url = format!("{{{{{base_var}}}}}{path}");

    // ---- query / header / cookie params ----
    let mut param_headers: Vec<KeyValue> = Vec::new();
    let mut cookies: Vec<(String, bool)> = Vec::new();
    for p in &params {
        let Some(name) = p.get("name").and_then(Value::as_str) else { continue };
        let required = p.get("required").and_then(Value::as_bool).unwrap_or(false);
        let value = param_example(ctx, p);
        let description = if with_docs { param_doc(ctx, p, required) } else { String::new() };
        let mk = |n: String, v: String| KeyValue { enabled: required, name: n, value: v, description: description.clone() };
        match p.get("in").and_then(Value::as_str) {
            Some("query") => {
                for (n, v) in expand_query(name, &value, p) {
                    req.query.items.push(mk(n, encode_component(&v)));
                }
            }
            Some("header") => {
                if ["accept", "content-type", "authorization"].contains(&name.to_ascii_lowercase().as_str()) {
                    continue;
                }
                param_headers.push(mk(name.to_string(), single_line(&value_to_string(&value))));
            }
            Some("cookie") => cookies.push((format!("{name}={}", value_to_string(&value)), required)),
            _ => {}
        }
    }

    // ---- headers: Accept, Content-Type, params ----
    if let Some(accept) = accept_type(ctx, o) {
        req.headers.items.push(KeyValue::new("Accept", accept));
    }
    if let Some((content_type, body)) = build_body(ctx, o) {
        req.headers.items.push(KeyValue::new("Content-Type", content_type));
        req.body = body;
    }
    req.headers.items.extend(param_headers);

    // ---- auth ----
    apply_security(ctx, op, &mut req, &mut cookies, secrets);

    if !cookies.is_empty() {
        let enabled = cookies.iter().any(|(_, r)| *r);
        let value = cookies.into_iter().map(|(c, _)| c).collect::<Vec<_>>().join("; ");
        req.headers.items.push(KeyValue { enabled, name: "Cookie".into(), value, ..Default::default() });
    }
    req
}

fn expand_query(name: &str, value: &Value, p: &Value) -> Vec<(String, String)> {
    let style = p.get("style").and_then(Value::as_str).unwrap_or("form");
    let explode = p.get("explode").and_then(Value::as_bool).unwrap_or(style == "form");
    match value {
        Value::Array(items) if items.is_empty() => vec![(name.to_string(), String::new())],
        Value::Array(items) if explode => items.iter().map(|i| (name.to_string(), value_to_string(i))).collect(),
        Value::Array(items) => {
            let sep = match style {
                "pipeDelimited" => "|",
                "spaceDelimited" => " ",
                _ => ",",
            };
            vec![(name.to_string(), items.iter().map(value_to_string).collect::<Vec<_>>().join(sep))]
        }
        Value::Object(map) if style == "deepObject" => {
            map.iter().map(|(k, v)| (format!("{name}[{k}]"), value_to_string(v))).collect()
        }
        Value::Object(map) if explode => map.iter().map(|(k, v)| (k.clone(), value_to_string(v))).collect(),
        Value::Object(map) => vec![(
            name.to_string(),
            map.iter().flat_map(|(k, v)| [k.clone(), value_to_string(v)]).collect::<Vec<_>>().join(","),
        )],
        other => vec![(name.to_string(), value_to_string(other))],
    }
}

fn accept_type<'a>(ctx: &Ctx<'a>, op: &'a Value) -> Option<String> {
    let responses = op.get("responses")?.as_object()?;
    responses
        .iter()
        .filter(|(code, _)| code.starts_with('2'))
        .find_map(|(_, r)| ctx.deref(r).get("content")?.as_object()?.keys().next().cloned())
}

fn is_json(mt: &str) -> bool {
    let mt = mt.to_ascii_lowercase();
    mt == "application/json" || mt.ends_with("+json") || mt.contains("/json")
}

fn pick_media_type(content: &Map<String, Value>) -> Option<&String> {
    let keys: Vec<&String> = content.keys().collect();
    let find = |pred: &dyn Fn(&str) -> bool| keys.iter().copied().find(|k| pred(&k.to_ascii_lowercase()));
    find(&|k| k == "application/json")
        .or_else(|| find(&|k| is_json(k)))
        .or_else(|| find(&|k| k == "application/x-www-form-urlencoded"))
        .or_else(|| find(&|k| k.starts_with("multipart/")))
        .or_else(|| find(&|k| k.contains("xml")))
        .or_else(|| find(&|k| k.starts_with("text/")))
        .or_else(|| keys.first().copied())
}

fn build_body<'a>(ctx: &Ctx<'a>, op: &'a Value) -> Option<(String, Body)> {
    let rb = ctx.deref(op.get("requestBody")?);
    let content = rb.get("content")?.as_object()?;
    let media_type = pick_media_type(content)?.clone();
    let media = ctx.deref(&content[&media_type]);
    let schema = media.get("schema");
    let example = object_example(ctx, media);
    let lower = media_type.to_ascii_lowercase();
    let schema_obj = schema.map(|s| ctx.deref(s)).and_then(Value::as_object);

    let (content_type, mode, text) = if is_json(&lower) {
        let value = match example {
            Some(Value::String(s)) => serde_json::from_str(&s).unwrap_or(Value::String(s)),
            Some(Value::Null) | None => Value::Object(Map::new()),
            Some(v) => v,
        };
        (media_type.clone(), BodyMode::Json, serde_json::to_string_pretty(&value).unwrap_or_default())
    } else if lower.starts_with("multipart/") {
        let ct = format!("{media_type}; boundary={BOUNDARY}");
        (ct, BodyMode::Multipart, multipart_body(ctx, schema, example, media.get("encoding")))
    } else if lower == "application/x-www-form-urlencoded" {
        let text = match example {
            Some(Value::Object(map)) => form_body(&map),
            Some(v) => value_to_string(&v),
            None => String::new(),
        };
        (media_type.clone(), BodyMode::FormUrlEncoded, text)
    } else if lower.contains("xml") {
        let text = match example {
            Some(Value::String(s)) => s,
            Some(v) => {
                let root_name = schema
                    .and_then(|s| ctx.resolve(s).1)
                    .and_then(|r| r.rsplit('/').next())
                    .map(str::to_string)
                    .or_else(|| {
                        schema_obj.and_then(|s| s.get("xml")?.get("name")?.as_str().map(str::to_string))
                    })
                    .unwrap_or_else(|| "root".into());
                format!("<?xml version=\"1.0\" encoding=\"UTF-8\"?>\n{}", to_xml(&root_name, &v, 0))
            }
            None => String::new(),
        };
        (media_type.clone(), BodyMode::Xml, text)
    } else if lower.starts_with("text/") {
        let text = example.map(|v| value_to_string(&v)).unwrap_or_default();
        let text = if text.is_empty() { "text".into() } else { text };
        (media_type.clone(), BodyMode::Text, text)
    } else {
        let binary = lower.contains('*')
            || lower == "application/octet-stream"
            || ["image/", "audio/", "video/", "font/"].iter().any(|p| lower.starts_with(p))
            || lower == "application/pdf"
            || lower == "application/zip"
            || schema_obj.is_some_and(is_binary);
        let ct = if lower.contains('*') { "application/octet-stream".to_string() } else { media_type.clone() };
        if binary {
            (ct, BodyMode::File, format!("< ./body.{}", extension_for(&lower)))
        } else {
            let text = match example {
                Some(Value::String(s)) => s,
                Some(v) => serde_json::to_string_pretty(&v).unwrap_or_default(),
                None => String::new(),
            };
            (ct, BodyMode::Raw, text)
        }
    };
    Some((content_type, Body { enabled: true, mode, text: indent_http_syntax(&text) }))
}

/// Indents example lines that `.http` syntax would read as a request separator
/// or response handler, so the generated request stays one request.
fn indent_http_syntax(text: &str) -> String {
    let collides = |l: &str| parser::is_separator(l) || parser::is_handler_start(l);
    if !text.lines().any(collides) {
        return text.to_string();
    }
    text.split('\n').map(|l| if collides(l) { format!(" {l}") } else { l.to_string() }).collect::<Vec<_>>().join("\n")
}

fn extension_for(media_type: &str) -> &'static str {
    match media_type.split(';').next().unwrap_or("").trim() {
        "image/png" => "png",
        "image/jpeg" | "image/jpg" => "jpg",
        "image/gif" => "gif",
        "image/svg+xml" => "svg",
        "image/webp" => "webp",
        "application/pdf" => "pdf",
        "application/zip" => "zip",
        "application/json" => "json",
        "text/plain" => "txt",
        "text/csv" => "csv",
        _ => "bin",
    }
}

fn form_body(map: &Map<String, Value>) -> String {
    let mut pairs = Vec::new();
    for (k, v) in map {
        match v {
            Value::Array(items) => {
                for i in items {
                    pairs.push(format!("{}={}", encode_component(k), encode_component(&value_to_string(i))));
                }
            }
            other => pairs.push(format!("{}={}", encode_component(k), encode_component(&value_to_string(other)))),
        }
    }
    pairs.join("&")
}

fn multipart_body<'a>(ctx: &Ctx<'a>, schema: Option<&'a Value>, example: Option<Value>, encoding: Option<&'a Value>) -> String {
    let props = schema.map(|s| ctx.properties(s)).unwrap_or_default();
    let example_map = match &example {
        Some(Value::Object(m)) => m.clone(),
        _ => Map::new(),
    };
    let mut names: Vec<String> = props
        .iter()
        .filter(|(_, s)| s.get("readOnly").and_then(Value::as_bool) != Some(true))
        .map(|(n, _)| n.to_string())
        .collect();
    for k in example_map.keys() {
        if !names.contains(k) {
            names.push(k.clone());
        }
    }
    let mut lines: Vec<String> = Vec::new();
    for name in &names {
        let prop = props.iter().find(|(n, _)| n == name).map(|(_, s)| *s);
        let prop_obj = prop.and_then(Value::as_object);
        let item_binary = prop_obj
            .and_then(|o| o.get("items"))
            .map(|i| ctx.deref(i))
            .and_then(Value::as_object)
            .is_some_and(is_binary);
        let binary = prop_obj.is_some_and(is_binary) || item_binary;
        let enc_type = encoding
            .and_then(|e| e.get(name))
            .and_then(|e| e.get("contentType"))
            .and_then(Value::as_str)
            .map(|s| s.split(',').next().unwrap_or(s).trim().to_string());

        lines.push(format!("--{BOUNDARY}"));
        if binary {
            let ct = enc_type.unwrap_or_else(|| "application/octet-stream".into());
            let file_name = format!("{name}.{}", extension_for(&ct));
            lines.push(format!("Content-Disposition: form-data; name=\"{name}\"; filename=\"{file_name}\""));
            lines.push(format!("Content-Type: {ct}"));
            lines.push(String::new());
            lines.push(format!("< ./{file_name}"));
            continue;
        }
        let value = example_map
            .get(name)
            .cloned()
            .or_else(|| prop.map(|p| ctx.schema_example(p)))
            .unwrap_or(Value::Null);
        let is_structured = matches!(value, Value::Object(_) | Value::Array(_))
            || prop_obj.and_then(schema_type).is_some_and(|t| t == "object");
        lines.push(format!("Content-Disposition: form-data; name=\"{name}\""));
        let ct = enc_type.or_else(|| is_structured.then(|| "application/json".to_string()));
        if let Some(ct) = ct {
            lines.push(format!("Content-Type: {ct}"));
        }
        lines.push(String::new());
        lines.push(if is_structured { value.to_string() } else { value_to_string(&value) });
    }
    lines.push(format!("--{BOUNDARY}--"));
    lines.join("\n")
}

fn xml_escape(s: &str) -> String {
    s.replace('&', "&amp;").replace('<', "&lt;").replace('>', "&gt;")
}

fn to_xml(name: &str, v: &Value, indent: usize) -> String {
    let pad = "  ".repeat(indent);
    match v {
        Value::Object(map) => {
            let mut out = format!("{pad}<{name}>\n");
            for (k, child) in map {
                out.push_str(&to_xml(k, child, indent + 1));
            }
            out.push_str(&format!("{pad}</{name}>\n"));
            if indent == 0 {
                out.trim_end().to_string()
            } else {
                out
            }
        }
        Value::Array(items) => {
            let out: String = items.iter().map(|i| to_xml(name, i, indent)).collect();
            if indent == 0 {
                format!("<{name}List>\n{}</{name}List>", items.iter().map(|i| to_xml(name, i, 1)).collect::<String>())
            } else {
                out
            }
        }
        other => {
            let line = format!("{pad}<{name}>{}</{name}>", xml_escape(&value_to_string(other)));
            if indent == 0 {
                line
            } else {
                line + "\n"
            }
        }
    }
}

fn push_secret(secrets: &mut Vec<String>, name: &str) {
    if !secrets.iter().any(|s| s == name) {
        secrets.push(name.to_string());
    }
}

fn apply_security<'a>(
    ctx: &Ctx<'a>,
    op: &Op<'a>,
    req: &mut Request,
    cookies: &mut Vec<(String, bool)>,
    secrets: &mut Vec<String>,
) {
    let requirements = op.op.get("security").or_else(|| ctx.root.get("security")).and_then(Value::as_array);
    let Some(requirement) = requirements
        .into_iter()
        .flatten()
        .filter_map(Value::as_object)
        .find(|r| !r.is_empty())
    else {
        return;
    };
    for scheme_name in requirement.keys() {
        let Some(scheme) = ctx.root.pointer(&format!("/components/securitySchemes/{}", scheme_name.replace('~', "~0").replace('/', "~1"))) else {
            ctx.warn(format!("Unknown security scheme `{scheme_name}`"));
            continue;
        };
        let scheme = ctx.deref(scheme);
        let auth_free = req.auth.kind == AuthKind::None;
        let s = |k: &str| scheme.get(k).and_then(Value::as_str).unwrap_or("");
        match s("type") {
            "http" => match s("scheme").to_ascii_lowercase().as_str() {
                "basic" if auth_free => {
                    req.auth = Auth { kind: AuthKind::Basic, username: "{{username}}".into(), password: "{{password}}".into(), ..Default::default() };
                    push_secret(secrets, "username");
                    push_secret(secrets, "password");
                }
                "bearer" if auth_free => {
                    req.auth = Auth { kind: AuthKind::Bearer, token: "{{token}}".into(), ..Default::default() };
                    push_secret(secrets, "token");
                }
                "basic" | "bearer" => {}
                other => {
                    let var = sanitize_var(scheme_name);
                    let scheme_word = if other.is_empty() { "Token".to_string() } else { capitalize(other) };
                    req.headers.items.push(KeyValue::new("Authorization", format!("{scheme_word} {{{{{var}}}}}")));
                    push_secret(secrets, &var);
                    ctx.warn(format!("Security scheme `{scheme_name}` (HTTP {other}) is generated as a plain Authorization header"));
                }
            },
            "oauth2" | "openIdConnect" => {
                if auth_free {
                    req.auth = Auth { kind: AuthKind::Bearer, token: "{{accessToken}}".into(), ..Default::default() };
                    push_secret(secrets, "accessToken");
                }
            }
            "apiKey" => {
                let var = sanitize_var(scheme_name);
                let key_name = s("name").to_string();
                let value = format!("{{{{{var}}}}}");
                push_secret(secrets, &var);
                let location = match s("in") {
                    "query" => Some(ApiKeyLocation::Query),
                    "header" => Some(ApiKeyLocation::Header),
                    _ => None,
                };
                match location {
                    Some(loc) if auth_free => {
                        req.auth = Auth { kind: AuthKind::ApiKey, key_name, key_value: value, key_location: loc, ..Default::default() };
                    }
                    Some(ApiKeyLocation::Query) => req.query.items.push(KeyValue::new(key_name, value)),
                    Some(ApiKeyLocation::Header) => req.headers.items.push(KeyValue::new(key_name, value)),
                    None => cookies.push((format!("{key_name}={value}"), true)),
                }
            }
            "mutualTLS" => ctx.warn(format!(
                "Security scheme `{scheme_name}` uses mutual TLS; configure a client certificate in the environment's SSLConfiguration"
            )),
            other => ctx.warn(format!("Unsupported security scheme type `{other}` for `{scheme_name}`")),
        }
    }
}

fn capitalize(s: &str) -> String {
    let mut c = s.chars();
    match c.next() {
        Some(f) => f.to_uppercase().collect::<String>() + c.as_str(),
        None => String::new(),
    }
}
